#!/usr/bin/env node
/**
 * Runs before every build. Reads every published project slug from the store API
 * (GET /v1/catalog/projects?fields=slug — one answer, all slugs, alphabetical) and writes:
 *   - routes.txt                    prerendered routes, /ar/ and /en/ (also the a11y sweep's list)
 *   - src/app/prerender-manifest.ts PROJECT_SLUGS for app.routes.server.ts (the one source of truth)
 *   - public/sitemap.xml, robots.txt canonical host https://store.ta3lom.sa, hreflang ar/en/x-default
 * C-1: build-time data comes from PRERENDER_API_URL (CI: the stub), separate from the runtime API URL compiled into the
 * app (environment.apiUrl). Falls back to STORE_API_URL, then the local API.
 * If the API is unreachable the build fails — a silent partial prerender is worse than no build.
 */
import { writeFileSync } from 'node:fs';

const API_URL = (process.env.PRERENDER_API_URL ?? process.env.STORE_API_URL ?? 'http://localhost:5080/v1').replace(/\/$/, '');
const SITE_ORIGIN = process.env.SITE_ORIGIN ?? 'https://store.ta3lom.sa';
const LOCALES = ['ar', 'en'];
const STATIC_ROUTES = ['/'];

async function apiJson(path) {
  let last;
  for (let attempt = 0; attempt < 4; attempt += 1) {
    try {
      const res = await fetch(`${API_URL}${path}`, { headers: { 'user-agent': 'ta3lom-store-build/1.0' } });
      if (res.ok) return res.json();
      last = new Error(`${path} -> HTTP ${res.status}`);
      if (res.status < 500 && res.status !== 429) break;
    } catch (err) {
      last = err;
    }
    await new Promise((r) => setTimeout(r, 1000 * 2 ** attempt));
  }
  throw last;
}

async function projectSlugs() {
  const body = await apiJson('/catalog/projects?fields=slug');
  if (!Array.isArray(body.slugs)) throw new Error('/catalog/projects?fields=slug did not return { slugs: [] }');
  return body.slugs.filter((s) => /^[a-z0-9-]{2,80}$/.test(s));
}

const localePath = (locale, route) => `/${locale}${route === '/' ? '/' : route}`;

let slugs;
try {
  slugs = await projectSlugs();
} catch (err) {
  console.error(`routes.mjs: could not read the catalogue from ${API_URL}: ${err instanceof Error ? err.message : err}`);
  console.error('A silent partial prerender is worse than no build — failing (start the API: npm run api:up, or the stub: npm run stub-api).');
  process.exit(1);
}
if (slugs.length === 0) {
  console.error('routes.mjs: the catalogue has no published project — refusing to build an empty store.');
  process.exit(1);
}

const routes = [...STATIC_ROUTES, ...slugs.map((s) => `/p/${s}`)];
const lines = LOCALES.flatMap((l) => routes.map((r) => localePath(l, r)));
writeFileSync('routes.txt', `${lines.join('\n')}\n`);

const urls = LOCALES.flatMap((l) =>
  routes.map((r) =>
    [
      '  <url>',
      `    <loc>${SITE_ORIGIN}${localePath(l, r)}</loc>`,
      ...LOCALES.map((a) => `    <xhtml:link rel="alternate" hreflang="${a}" href="${SITE_ORIGIN}${localePath(a, r)}" />`),
      `    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE_ORIGIN}${localePath('ar', r)}" />`,
      '  </url>',
    ].join('\n'),
  ),
);
writeFileSync(
  'public/sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${urls.join('\n')}\n</urlset>\n`,
);
writeFileSync(
  'public/robots.txt',
  `User-agent: *\nAllow: /\nDisallow: /ar/admin\nDisallow: /en/admin\nDisallow: /ar/account\nDisallow: /en/account\nDisallow: /ar/checkout\nDisallow: /en/checkout\nDisallow: /ar/cart\nDisallow: /en/cart\nDisallow: /ar/orders\nDisallow: /en/orders\nSitemap: ${SITE_ORIGIN}/sitemap.xml\n`,
);
writeFileSync(
  'src/app/prerender-manifest.ts',
  `// GENERATED by scripts/routes.mjs — do not hand-edit (re-run \`node scripts/routes.mjs\`, or \`npm run build\`).\n` +
    `// The single source of truth for prerendering: app.routes.server.ts reads PROJECT_SLUGS from here.\n\n` +
    `export const PROJECT_SLUGS: string[] = ${JSON.stringify(slugs)};\n\n` +
    `/** Every prerendered route, unprefixed by locale. */\n` +
    `export const ROUTES: string[] = ${JSON.stringify(routes)};\n`,
);
console.log(`routes.mjs: ${routes.length} routes (${STATIC_ROUTES.length} static + ${slugs.length} projects) × ${LOCALES.length} locales; sitemap, robots and prerender manifest written`);
