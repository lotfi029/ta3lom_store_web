#!/usr/bin/env node
/**
 * Generates the build's Caddy snippets from dist/ (owner H-3) — never hand-edited, never committed:
 *   dist/store-web/caddy/csp.conf   `header Content-Security-Policy "…"`: script-src 'self' + the sha256 of EVERY inline
 *                                   script the built pages carry (hash-only, never 'unsafe-inline'); connect-src, img-src
 *                                   and media-src = 'self' + the environment's API origin (+ the error-report origin when
 *                                   set); upgrade-insecure-requests when the API is https.
 *   dist/store-web/caddy/env.conf   per-environment headers: staging → `X-Robots-Tag: noindex, nofollow`.
 * The container image copies both to /etc/caddy/ (deploy/Caddyfile imports them); scripts/check-csp.mjs and
 * scripts/check-container.mjs read csp.conf. Environment from DEPLOY_ENV (scripts/lib/envs.mjs).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { deployEnv } from './lib/envs.mjs';
import { BROWSER_DIR, CADDY_DIR, inlineScriptHashes } from './lib/csp.mjs';

const env = deployEnv();
const api = new URL(env.apiUrl).origin;
const report = env.errorReportUrl ? new URL(env.errorReportUrl).origin : null;
const hashes = [...inlineScriptHashes(BROWSER_DIR).keys()].sort();
if (hashes.length === 0) {
  console.error('gen-csp: no inline script found in the build — is dist/store-web/browser there?');
  process.exit(1);
}
const connect = ["'self'", api, ...(report && report !== api ? [report] : [])];
const policy = [
  "default-src 'self'",
  `script-src 'self' ${hashes.join(' ')}`,
  "style-src 'self' 'unsafe-inline'",
  `img-src 'self' data: blob: ${api}`,
  "font-src 'self'",
  `connect-src ${connect.join(' ')}`,
  `media-src 'self' ${api}`,
  "frame-src 'none'",
  "frame-ancestors 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  ...(api.startsWith('https:') ? ['upgrade-insecure-requests'] : []),
].join('; ');

mkdirSync(CADDY_DIR, { recursive: true });
const banner = `# GENERATED by scripts/gen-csp.mjs for DEPLOY_ENV=${env.name} — do not edit, do not commit.\n`;
writeFileSync(join(CADDY_DIR, 'csp.conf'), `${banner}header Content-Security-Policy "${policy}"\n`);
writeFileSync(
  join(CADDY_DIR, 'env.conf'),
  banner + (env.robots === 'noindex' ? 'header X-Robots-Tag "noindex, nofollow"\n' : ''),
);
console.log(`gen-csp: [${env.name}] ${hashes.length} script hash(es); connect-src ${connect.join(' ')} → dist/store-web/caddy/`);
